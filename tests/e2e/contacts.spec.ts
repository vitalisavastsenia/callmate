  const prepare = button(page, 'Prepare the plan');
  await expect(page.locator('#home-readiness')).toHaveText('Add a goal, a name, a valid phone number to continue.');
  await expect(prepare).toBeDisabled();
  await expect(page.getByLabel('Country code', { exact: true })).toHaveValue('+34');
  await page.getByLabel('Home goal', { exact: true }).fill('Leave a message for the manager.');
  await expect(prepare).toBeDisabled();
  await page.getByLabel('Name', { exact: true }).fill('Clinic North');
  await expect(prepare).toBeDisabled();
  await page.getByLabel('Phone number', { exact: true }).fill('123-no');
  await expect(page.getByText('Enter a valid phone number', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveAttribute('aria-invalid', 'true');
  await expect(prepare).toBeDisabled();
  await page.getByLabel('Phone number', { exact: true }).fill('612 345-678');
  await expect(prepare).toBeEnabled();
  await expect(page.locator('#home-readiness')).toBeEmpty();
