test('Home saves a new contact only when opted in and sends the entered destination in E.164', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Home goal', { exact: true }).fill('Call Clinic Sol and ask about opening hours.');
  await page.getByLabel('Name', { exact: true }).fill('Clinic North');
  await page.getByLabel('Phone number', { exact: true }).fill('+44 20-7946 0958');
  await button(page, 'Prepare the plan').click();
  await expect(page.getByRole('region', { name: 'Zeus will…', exact: true })).toContainText('Clinic North');
  expect(await page.evaluate(() => localStorage.getItem('zeus-llama.contacts.v1'))).toBeNull();
  await page.getByLabel('Save to contacts', { exact: true }).check();
  await button(page, 'Prepare the plan').click();
  await expect(page.getByRole('region', { name: 'Zeus will…', exact: true })).toContainText('+442079460958');
  await expect(page.getByLabel('Save to contacts', { exact: true })).toHaveCount(0);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.contacts.v1')!));
  expect(saved).toHaveLength(1);
  expect(saved[0]).toMatchObject({ name: 'Clinic North', phone: '+442079460958', timeZone: 'Europe/London' });
  await button(page, 'Call').click();
  await expect(button(page, 'Stop call')).toBeVisible();
  const request = await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.simulator.v1')!).plans.at(-1).request);
  expect(request.business).toEqual({ name: 'Clinic North', phone: '+442079460958' });
  expect(request.contact_id).toBe(saved[0].id);
  await button(page, 'Stop call').click();
});
