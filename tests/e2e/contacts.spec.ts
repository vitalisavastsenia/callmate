import { expect, test, type Page } from '@playwright/test';
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true });
async function manual(page: Page) { await page.goto('/'); await button(page, 'Request').click(); }
async function basic(page: Page) {
  await page.getByLabel('Name', { exact: true }).fill('Clinic Sol');
  await page.getByLabel('Phone number', { exact: true }).fill('612345678');
  await page.getByRole('button', { name: 'Other', exact: true }).click();
  await page.getByLabel('Goal', { exact: true }).fill('Leave a message for the manager.');
}
async function upload(page: Page, name: string, text: string) {
  await page.getByRole('combobox', { name: 'Name', exact: true }).click();
  await page.getByRole('option', { name: 'Import contacts (.vcf / .csv)', exact: true }).click();
  await page.getByLabel('Contacts file', { exact: true }).setInputFiles({ name, mimeType: name.endsWith('.csv') ? 'text/csv' : 'text/vcard', buffer: Buffer.from(text) });
  await expect(page.getByRole('dialog', { name: 'Import contacts', exact: true })).toBeVisible();
}
test('contacts save only when opted in, prefill tone and notes, edit explicitly, and reach the call plan', async ({ page }) => {
  await manual(page); await basic(page);
  await button(page, 'Very polite').click(); await button(page, 'Formal').click();
  await page.getByLabel('Notes for Zeus', { exact: true }).fill('Be extra polite and patient.');
  await page.getByLabel('Save to contacts', { exact: true }).check();
  await button(page, 'Review call plan').click();
  await expect(page.getByRole('region', { name: 'Zeus will…', exact: true })).toContainText('very polite, formal');
  await expect(page.getByRole('region', { name: 'Zeus will…', exact: true })).toContainText('Be extra polite and patient.');
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.contacts.v1')!));
  expect(saved).toHaveLength(1);
  await page.reload(); await button(page, 'Request').click();
  const picker = page.getByRole('combobox', { name: 'Name', exact: true });
  await picker.fill('sol'); await page.keyboard.press('Enter');
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Clinic Sol');
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveValue('612345678');
  await expect(button(page, 'Very polite')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByLabel('Notes for Zeus', { exact: true })).toHaveValue('Be extra polite and patient.');
  await page.getByRole('button', { name: 'Other', exact: true }).click();
  await page.getByLabel('Goal', { exact: true }).fill('Leave a message for the manager.');
  await page.getByLabel('Notes for Zeus', { exact: true }).fill('New request-only note.');
  await button(page, 'Review call plan').click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.contacts.v1')!)[0].notes)).toBe('Be extra polite and patient.');
  await button(page, 'Edit selected contact').click();
  await page.getByRole('dialog').getByLabel('Notes for Zeus', { exact: true }).fill('New request-only note.');
  await page.getByRole('dialog').getByRole('button', { name: 'Save contact', exact: true }).click();
  await button(page, 'Review call plan').click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.contacts.v1')!)[0].notes)).toBe('New request-only note.');
  await button(page, 'Call').click();
  await expect(button(page, 'Stop call')).toBeVisible();
  const request = await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.simulator.v1')!).plans.at(-1).request);
  expect(request.tone).toEqual(['Very polite', 'Formal "usted"']); expect(request.tone_notes).toBe('New request-only note.'); expect(request.contact_id).toBe(saved[0].id);
  await button(page, 'Stop call').click();
});
test('CSV/vCard imports map columns, skip phone duplicates, and support edit, Escape, and delete', async ({ page }) => {
  await manual(page);
  await upload(page, 'contacts.csv', 'Company,Number\nClinic Sol,612345678\nDuplicate,+34 612 345 678\nBad,invalid');
  const dialog = page.getByRole('dialog', { name: 'Import contacts', exact: true });
  await dialog.getByLabel('Name column', { exact: true }).selectOption('0');
  await dialog.getByLabel('Phone column', { exact: true }).selectOption('1');
  await dialog.getByRole('button', { name: 'Import contacts', exact: true }).click();
  await expect(page.getByText('1 imported · 1 duplicate phone numbers skipped · 1 invalid rows skipped.', { exact: true })).toBeVisible();
  await expect(page.locator('.manual-request [role="alert"]')).toHaveCount(0);
  await upload(page, 'contacts.vcf', 'BEGIN:VCARD\nVERSION:3.0\nFN:Duplicate\nTEL:+34612345678\nEND:VCARD\nBEGIN:VCARD\nFN:Barber Luna\nTEL:+34612345679\nEND:VCARD');
  await page.getByRole('dialog').getByRole('button', { name: 'Import contacts', exact: true }).click();
  await expect(page.getByText('1 imported · 1 duplicate phone numbers skipped · 0 invalid rows skipped.', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Name' }).fill('luna');
  await page.getByRole('option', { name: /Barber Luna/ }).click();
  await button(page, 'Edit selected contact').click();
  await expect(page.getByRole('dialog', { name: 'Edit contact' })).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).toHaveCount(0);
  await button(page, 'Edit selected contact').click();
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Barber Luna Updated');
  await page.getByRole('dialog').getByLabel('Notes for Zeus', { exact: true }).fill('Patient and friendly.');
  await page.getByRole('dialog').getByRole('button', { name: 'Save contact', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Barber Luna Updated');
  await expect(page.getByLabel('Notes for Zeus', { exact: true })).toHaveValue('Patient and friendly.');
  await expect(page.locator('.manual-request [role="alert"]')).toHaveCount(0);
  await button(page, 'Edit selected contact').click(); await page.getByRole('dialog').getByRole('button', { name: 'Delete contact', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(button(page, 'Edit selected contact')).toHaveCount(0);
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Barber Luna Updated');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zeus-llama.contacts.v1')!).length)).toBe(1);
  await page.screenshot({ path: test.info().outputPath('contacts-request.png'), fullPage: true });
});
